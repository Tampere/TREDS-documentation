'use client';

import { useRef, useState } from 'react';
import { useRouter } from 'next/navigation';
import { SearchField } from '@tampere/treds';
import { dict, type Lang } from '@/i18n';

interface PagefindResult {
  url: string;
  excerpt: string;
  meta: { title: string };
  sub_results: { url: string; title: string; excerpt: string }[];
}
interface Pagefind {
  debouncedSearch: (
    q: string,
    opts?: object,
    ms?: number
  ) => Promise<{ results: { data: () => Promise<PagefindResult> }[] } | null>;
}

// Matches SearchField's SearchFieldData constraint, which TREDS 1.0.0 doesn't export.
interface Hit {
  value: string;
  label: string;
  url: string;
}

const MAX_RESULTS = 8;

// The index is generated by `pagefind` after `next build`, so it only exists in the built
// site, not in `next dev`. Loaded on first keystroke, outside the bundler's module graph.
async function loadPagefind(): Promise<Pagefind | null> {
  try {
    const url = '/pagefind/pagefind.js';
    return await import(/* webpackIgnore: true */ /* turbopackIgnore: true */ url);
  } catch {
    return null;
  }
}

export function DocsSearch({ lang }: { lang: Lang }) {
  const t = dict[lang];
  const router = useRouter();
  const pagefind = useRef<Promise<Pagefind | null> | null>(null);
  const [hits, setHits] = useState<Hit[]>([]);
  const [loading, setLoading] = useState(false);

  async function search(query: string) {
    if (!query.trim()) return setHits([]);
    pagefind.current ??= loadPagefind();
    const pf = await pagefind.current;
    if (!pf) return setHits([]);
    setLoading(true);
    const response = await pf.debouncedSearch(query);
    // null means a newer keystroke superseded this search.
    if (!response) return;
    const pages = await Promise.all(response.results.slice(0, MAX_RESULTS).map((r) => r.data()));
    // SearchField keys options by label, so labels must be unique: the section heading
    // is part of the label for a sub-result.
    const next = pages.flatMap((page) => {
      // A sub-result titled like the page is its h1 anchor: link to the page itself instead.
      const best = page.sub_results.find((s) => s.title !== page.meta.title);
      const url = best?.url ?? page.url;
      const label = best ? `${page.meta.title} › ${best.title}` : page.meta.title;
      return [{ value: url, url, label }];
    });
    setHits(next.filter((h, i) => next.findIndex((o) => o.label === h.label) === i));
    setLoading(false);
  }

  return (
    <SearchField<Hit>
      aria-label={t.search}
      placeholder={t.search}
      data={hits}
      isLoading={loading}
      fillAvailableSpace
      searchOnItemSelect
      clearButtonLabel={t.clear}
      searchButtonLabel={t.searchButton}
      onChange={(e) => search(e.currentTarget.value)}
      onClearClick={() => setHits([])}
      onSearch={(hit) => router.push(hit.url)}
    />
  );
}
